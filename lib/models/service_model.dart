class ServiceModel {
  final String id;
  final String name;
  final String category;
  final String duration;
  final double price;
  final String icon;
  final String description;

  const ServiceModel({
    required this.id,
    required this.name,
    required this.category,
    required this.duration,
    required this.price,
    required this.icon,
    required this.description,
  });
}